"""Backtesting against publicly documented incidents (spec section 6.4).

Hits and misses are reported with equal prominence. Metrics must not be tuned to this set
without documenting it; incidents marked ``split: holdout`` are kept for honest evaluation.
"""

from __future__ import annotations

from datetime import date, datetime
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel, Field

from toolcensus.diff.engine import diff_servers, supply_chain_signals
from toolcensus.discovery import npm
from toolcensus.discovery.http import HttpError
from toolcensus.metrics.supply_chain import release_times
from toolcensus.models import ObservedVia, ServerRecord, Status
from toolcensus.pipeline import ScanContext, introspect_version
from toolcensus.storage.snapshots import SnapshotStore, append_jsonl


class Incident(BaseModel):
    id: str
    package: str
    affected_versions: list[str]
    disclosed: date
    kind: str
    description: str
    references: list[str]
    split: Literal["dev", "holdout"] = "dev"


class BacktestResult(BaseModel):
    incident: Incident
    hit: bool
    signals: list[str] = Field(default_factory=list)
    lead_days: int | None = None
    reason: str
    versions_examined: list[str] = Field(default_factory=list)


def load_incidents(path: Path) -> list[Incident]:
    data = yaml.safe_load(path.read_text()) or {}
    return [Incident.model_validate(i) for i in data.get("incidents", [])]


async def _record_for(
    ctx: ScanContext | None, store: SnapshotStore, pack: dict[str, Any], version: str
) -> ServerRecord | None:
    name = str(pack["name"])
    for rec in store.read_backfill(name):
        if rec.package.version == version:
            return rec
    if ctx is None:
        return None
    rec = await introspect_version(ctx, pack, version, observed_via=ObservedVia.BACKFILL)
    append_jsonl(store.backfill_path(name), rec)
    return rec


async def evaluate(
    incident: Incident, store: SnapshotStore, ctx: ScanContext | None, *, preceding: int = 2
) -> BacktestResult:
    """``ctx=None`` evaluates purely from committed backfill data (no sandbox, no network)."""
    pack: dict[str, Any]
    times: dict[str, datetime]
    try:
        if ctx is None:
            raise HttpError(incident.package, 0)
        pack = await npm.packument(ctx.http, incident.package)
        times = release_times(pack)
    except HttpError:
        stored = store.read_backfill(incident.package)
        pack = {"name": incident.package, "versions": {}}
        times = {
            r.package.version: r.package.published_at for r in stored if r.package.published_at
        }

    affected = [v for v in incident.affected_versions if v in times]
    if not affected:
        return BacktestResult(
            incident=incident,
            hit=False,
            reason="affected versions are no longer available on npm (unpublished) or not in committed data",
        )
    ordered = sorted(times, key=lambda v: times[v])
    first = min(affected, key=lambda v: times[v])
    idx = ordered.index(first)
    window = ordered[max(0, idx - preceding) : idx + 1]

    recs: list[ServerRecord] = []
    for v in window:
        rec = await _record_for(ctx, store, pack, v)
        if rec is not None:
            recs.append(rec)
    if len(recs) < 2:
        return BacktestResult(
            incident=incident,
            hit=False,
            versions_examined=window,
            reason="no preceding version available to compare against",
        )

    prev, cur = recs[-2], recs[-1]
    signals = supply_chain_signals(prev.supply_chain, cur.supply_chain)
    signals += [f"{c.change_type.value}: {c.tool}" for c in diff_servers(prev, cur)]
    if prev.introspection.status is Status.OK and cur.introspection.status is not Status.OK:
        signals.append(f"introspection status changed to {cur.introspection.status.value}")

    lead = (incident.disclosed - times[first].date()).days if signals else None
    if signals:
        reason = f"{len(signals)} signal(s) changed at {first}"
    elif cur.introspection.status is not Status.OK:
        reason = f"could not introspect affected version ({cur.introspection.status.value})"
    else:
        reason = "tool definitions and package-level signals unchanged (change was likely in code)"
    return BacktestResult(
        incident=incident,
        hit=bool(signals),
        signals=signals,
        lead_days=lead,
        reason=reason,
        versions_examined=window,
    )


def render_markdown(results: list[BacktestResult]) -> str:
    hits = [r for r in results if r.hit]
    lines = [
        "# Backtest scorecard",
        "",
        "Generated by `toolcensus backtest` from committed data. Hits and misses are listed with",
        "equal prominence. A *hit* means at least one neutral signal changed at the first affected",
        "version; it does **not** mean ToolCensus would have identified the incident as malicious.",
        "",
        f"**{len(hits)} / {len(results)}** incidents had at least one signal change.",
        "",
        "| Incident | Split | Package | Result | Lead time (days) | Signals / reason |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        detail = "; ".join(r.signals) if r.signals else r.reason
        lines.append(
            f"| {r.incident.id} | {r.incident.split} | `{r.incident.package}` | "
            f"{'hit' if r.hit else 'miss'} | {r.lead_days if r.lead_days is not None else '—'} | {detail} |"
        )
    lines += ["", "## Incidents", ""]
    for r in results:
        refs = ", ".join(f"<{u}>" for u in r.incident.references)
        lines.append(
            f"- **{r.incident.id}** ({r.incident.disclosed}): {r.incident.description} {refs}"
        )
    return "\n".join(lines) + "\n"
